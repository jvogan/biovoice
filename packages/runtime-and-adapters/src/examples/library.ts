export function getExampleCatalog(): RecipeManifest[] {
  return exampleCatalog;
}

export function getRecipe(recipeId: string): RecipeManifest {
  const match = exampleCatalog.find((recipe) => recipe.id === recipeId);
  if (!match) {
    throw new Error(`Unknown recipe: ${recipeId}`);
  }
  return match;
}

export function getRecipeStep(recipeId: string, stepId: string, target: TargetKind) {
  const recipe = getRecipe(recipeId);
  if (!recipe.apps.includes(target)) {
    throw new Error(`Recipe ${recipeId} is not available for ${target}.`);
  }
  const step = recipe.steps.find((entry) => entry.id === stepId);
  if (!step) {
    throw new Error(`Unknown step ${stepId} for recipe ${recipeId}.`);
  }
  return step;
}
