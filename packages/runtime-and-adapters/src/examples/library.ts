function withVoicePack(
  app: TargetKind,
  specific: string[],
  themes: Array<"comparison" | "design" | "map"> = [],
) {
  const shared = app === "pymol" ? sharedPymolUtterances : sharedChimeraXUtterances;
  const themed = app === "pymol"
    ? [
        ...(themes.includes("comparison") ? sharedPymolComparisonUtterances : []),
        ...(themes.includes("design") ? sharedPymolDesignUtterances : []),
        ...(themes.includes("map") ? sharedPymolMapUtterances : []),
      ]
    : [
        ...(themes.includes("comparison") ? sharedChimeraXComparisonUtterances : []),
        ...(themes.includes("design") ? sharedChimeraXDesignUtterances : []),
        ...(themes.includes("map") ? sharedChimeraXMapUtterances : []),
      ];
  return [...specific, ...themed, ...shared];
}

